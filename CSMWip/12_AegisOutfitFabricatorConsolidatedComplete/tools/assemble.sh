#!/usr/bin/env bash
# assemble.sh — build deliverables/MASTER_SPECIFICATION.md from the product files.
#
# Product layout rule: edition specifications (DOC-11..DOC-20) are delivered as
# one file per chapter under specifications/edition_specifications/chapters/<DOC>/.
# For those documents the chapter files are the canonical text and the combined
# <DOC>_*.md file is a convenience roll-up, so the assembler uses the chapters.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/deliverables/MASTER_SPECIFICATION.md"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

CHAPTER_DOCS="DOC-11 DOC-12 DOC-13 DOC-14 DOC-15 DOC-16 DOC-17 DOC-18 DOC-19 DOC-20"

is_chapter_doc() {
  case " $CHAPTER_DOCS " in *" $1 "*) return 0 ;; *) return 1 ;; esac
}

emit() {
  printf '\n\n<!-- ===== SOURCE: %s ===== -->\n\n' "${1#"$ROOT/"}"
  cat "$1"
}

{
  echo "# AEGIS OUTFIT FABRICATOR — CONSOLIDATED MASTER SPECIFICATION"
  echo
  echo "> Generated by tools/assemble.sh from specifications/ and research/."
  echo "> Do not edit this file by hand; edit the product files instead."
  echo

  for group in core_architecture edition_specifications threat_protection integration_sustainment materials synthesis draft_kernels; do
    dir="$ROOT/specifications/$group"
    [ -d "$dir" ] || continue
    printf '\n\n# ===== %s =====\n' "$group"

    find "$dir" -maxdepth 1 -name '*.md' -print0 | sort -z | while IFS= read -r -d '' f; do
      doc="$(basename "$f" | cut -d_ -f1)"
      is_chapter_doc "$doc" && continue
      emit "$f"
    done

    chapters="$dir/chapters"
    [ -d "$chapters" ] || continue
    for docdir in "$chapters"/*; do
      [ -d "$docdir" ] || continue
      find "$docdir" -maxdepth 1 -name '*.md' -print0 | sort -z | while IFS= read -r -d '' f; do
        emit "$f"
      done
    done
  done

  printf '\n\n# ===== research =====\n'
  find "$ROOT/research" -maxdepth 1 -name '*.md' -print0 | sort -z | while IFS= read -r -d '' f; do
    emit "$f"
  done
} > "$TMP"

mkdir -p "$ROOT/deliverables"
mv "$TMP" "$OUT"
chmod 644 "$OUT"
printf 'wrote %s (%s lines)\n' "${OUT#"$ROOT/"}" "$(wc -l < "$OUT")"
